function operatorTargets(): Record<string, readonly UpstreamTarget[]> {
  return Object.fromEntries(operatorNames.map(name => [
    `@astryx.powersearch.operator.${name}`,
    [{ path: `powerSearch.operators.${name}` }],
  ]))
}

function valueTargets(): Record<string, readonly UpstreamTarget[]> {
  return Object.fromEntries(valueNames.map(name => [
    `@astryx.powersearch.valueEditor.${name}`,
    [{ path: `powerSearch.value.${name}` }],
  ]))
}

