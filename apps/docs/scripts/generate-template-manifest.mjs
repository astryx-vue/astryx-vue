const CATEGORY_RE = /category:\s*['"]([^'"]+)['"]/
const NAME_RE = /name:\s*['"]([^'"]+)['"]/

function categoryGroup(category) {
  const dash = category.indexOf(' - ')
  return dash === -1 ? category : category.slice(0, dash)
}

const entries = ORDER.map((slug) => {
  const docPath = path.join(UPSTREAM, slug, 'template.doc.mjs')
  const doc = fs.readFileSync(docPath, 'utf8')
  const categoryRaw = doc.match(CATEGORY_RE)?.[1] ?? ''
  const nameEn = doc.match(NAME_RE)?.[1] ?? slug
  const groupEn = categoryGroup(categoryRaw)
  const categoryZh = CATEGORY_ZH[groupEn] ?? groupEn
  const nameZh = NAME_ZH[nameEn] ?? nameEn
  return { slug, categoryEn: categoryRaw, groupEn, nameEn, categoryZh, nameZh }
})

const body = `// Generated by apps/docs/scripts/generate-template-manifest.mjs — do not edit by hand.
import type { PlaygroundLocale } from './protocol'

export const PLAYGROUND_TEMPLATE_SLUGS = [
${ORDER.map(s => `  '${s}',`).join('\n')}
] as const

export type PlaygroundTemplateSlug = typeof PLAYGROUND_TEMPLATE_SLUGS[number]

export interface PlaygroundTemplateMeta {
  slug: PlaygroundTemplateSlug
  categoryEn: string
  groupEn: string
  nameEn: string
  categoryZh: string
  nameZh: string
}

export const PLAYGROUND_TEMPLATE_META: Record<PlaygroundTemplateSlug, PlaygroundTemplateMeta> = {
${entries.map(e => `  '${e.slug}': {
    slug: '${e.slug}',
    categoryEn: ${JSON.stringify(e.categoryEn)},
    groupEn: ${JSON.stringify(e.groupEn)},
    nameEn: ${JSON.stringify(e.nameEn)},
    categoryZh: ${JSON.stringify(e.categoryZh)},
    nameZh: ${JSON.stringify(e.nameZh)},
  },`).join('\n')}
}

export function playgroundTemplateMenuLabel(
  meta: PlaygroundTemplateMeta,
  locale: PlaygroundLocale,
): string {
  if (meta.slug === 'theme-showcase')
    return locale === 'zh' ? meta.nameZh : meta.nameEn
  const group = locale === 'zh' ? meta.categoryZh : meta.groupEn
  const name = locale === 'zh' ? meta.nameZh : meta.nameEn
  if (name.toLowerCase() === group.toLowerCase())
    return name
  return \`\${group} · \${name}\`
}
`

fs.writeFileSync(OUT, body)
