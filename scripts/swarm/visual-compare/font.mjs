export const GLYPH_WIDTH = 5
export const GLYPH_HEIGHT = 7
const ADVANCE = GLYPH_WIDTH + 1

/** 文字按 scale 倍放大后的像素宽度。 */
export function textWidth(text, scale) {
  return Math.max(0, text.length * ADVANCE - 1) * scale
}

/**
 * 在 RGBA 缓冲区上画一行文字。
 * @param {{ data: Buffer, width: number, height: number }} image pngjs 的 PNG 对象或同形状对象
 */
export function drawText(image, text, x, y, scale, [r, g, b]) {
  const chars = text.toUpperCase()
  for (let i = 0; i < chars.length; i++) {
    const glyph = GLYPHS[chars[i]]
    if (!glyph)
      continue
    const left = x + i * ADVANCE * scale
    for (let row = 0; row < GLYPH_HEIGHT; row++) {
      for (let col = 0; col < GLYPH_WIDTH; col++) {
        if (glyph[row][col] !== '#')
          continue
        for (let dy = 0; dy < scale; dy++) {
          for (let dx = 0; dx < scale; dx++) {
            const px = left + col * scale + dx
            const py = y + row * scale + dy
            if (px < 0 || py < 0 || px >= image.width || py >= image.height)
              continue
            const offset = (py * image.width + px) * 4
            image.data[offset] = r
            image.data[offset + 1] = g
            image.data[offset + 2] = b
            image.data[offset + 3] = 255
          }
        }
      }
    }
  }
}
